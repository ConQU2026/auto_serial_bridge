def generate_crc8_table():
    """生成 CRC8 查找表（多项式 0x31）。"""
    polynomial = 0x31
    table = []
    for i in range(256):
        crc = i
        for _ in range(8):
            if crc & 0x80:
                crc = (crc << 1) ^ polynomial
            else:
                crc = crc << 1
        table.append(crc & 0xFF)
    return table


def _crc8_table_lines(indent):
    table = generate_crc8_table()
    lines = []
    for i in range(0, 256, 16):
        row = ", ".join(f"0x{value:02X}" for value in table[i:i + 16])
        lines.append(f"{indent}{row},")
    return "\n".join(lines)


def get_c_type(yaml_type, type_mappings):
    """把 YAML 类型别名解析为 C 类型；不在映射表中时原样返回。"""
    return type_mappings.get(yaml_type, yaml_type)


def merge_messages(config_data):
    """业务消息 + 内置系统消息，统一按 ID 排序后用于生成。"""
    business = config_data.get('messages', []) or []
    injected = [
        dict(message, fields=[dict(field) for field in message['fields']])
        for message in SYSTEM_MESSAGES
    ]
    return sorted(list(business) + injected, key=lambda m: m['id'])


def ros_message_packages(config_data):
    """Return sorted unique package names referenced by ros_msg entries."""
    return sorted({
        message['ros_msg'].split('/', 1)[0]
        for message in config_data.get('messages', []) or []
        if isinstance(message, dict) and isinstance(message.get('ros_msg'), str)
    })


def message_payload_size(message, type_mappings):
    """计算协议结构体 payload 大小，不含 reliable seq。"""
    return sum(
        _C_TYPE_SIZES.get(get_c_type(field['type'], type_mappings), 1)
        for field in message['fields']
    )


def message_wire_payload_size(message, type_mappings):
    """计算链路上传输的 payload 大小，reliable 消息额外包含 1 字节 seq。"""
    base_size = message_payload_size(message, type_mappings)
    if message.get('reliable', False):
        return base_size + 1
    return base_size


