        f.write(f"| 强制握手 | `{'是' if require_handshake else '否'}` |\n")
        f.write(f"| 协议哈希（握手用）| `0x{protocol_hash:08X}` |\n")
        f.write(f"| 严格心跳模式 | `{'是' if strict_heartbeat else '否'}` |\n")
        f.write(f"| 心跳发送间隔（ROS 端发起）| `{heartbeat_interval_ms} ms` |\n")
        f.write(f"| 心跳超时时间 | `{heartbeat_timeout_ms} ms` |\n")
        f.write(f"| 可靠传输重试间隔 | `{reliable_retry_interval_ms} ms` |\n")
        f.write(f"| 可靠传输重试告警阈值 | 每 `{reliable_max_retries} 次`告警一次，收到 ACK 前持续重试 |\n")
        f.write("\n---\n\n")

        f.write("## 帧格式\n\n")
        f.write("每帧结构如下（小端序）：\n\n")
        f.write("| 字节位置 | 字段 | 说明 |\n")
        f.write("| :------: | :--- | :--- |\n")
        f.write(f"| 0 | Header1 | 固定 `{head1:#04x}` |\n")
        f.write(f"| 1 | Header2 | 固定 `{head2:#04x}` |\n")
        f.write("| 2 | ID | 消息 ID，见下表 |\n")
        f.write("| 3 | Len | 数据段字节数 |\n")
        f.write("| 4 … 4+Len-1 | Data | 各字段按结构体内存布局排列 |\n")
        checksum_desc = _CHECKSUM_DESC.get(checksum, checksum)
        f.write(f"| 4+Len | Checksum | {checksum_desc} |\n")
        f.write("\n---\n\n")

        f.write("## MCU 集成注意事项\n\n")
        f.write("- 系统消息无需编写代码：心跳回包、握手回应、可靠消息 ACK 均由生成的协议状态机自动完成。\n")
        f.write("- 协议层会在 `protocol_fsm_feed()` 的调用上下文中发送回包。若 `protocol_fsm_feed()` "
                "在串口中断中调用，而业务代码在主循环中调用 `send_xxx()`，"
                "`serial_write()` 必须自行保证可重入/并发安全（如关中断保护或发送队列）。\n")
        f.write("- 心跳由 ROS 端周期发起并在超时窗口内重发同一 `count`，MCU 侧对重复心跳原样回包即可（自动完成）。\n")
        f.write("\n---\n\n")

        f.write("## 电控 → ROS（电控主动发送）\n\n")
        if rx_msgs:
            for msg in rx_msgs:
                total_bytes = message_payload_size(msg, type_mappings)
                f.write(f"### `{msg['name']}` — ID `{msg['id']:#04x}`\n\n")
                _write_message_meta(f, msg, 'pub_topic')
                f.write(f"- **数据段字节数（Len）**：`{total_bytes}`\n")
                if msg.get('notes'):
                    f.write(f"- **注意事项**：{msg['notes']}\n")
                if msg['name'] == 'Handshake' and require_handshake:
                    f.write("- **内置行为**：协议层收到握手包后自动回传本机 `PROTOCOL_HASH`，是否匹配由 ROS 端校验，MCU 侧无需编写代码。\n")
                f.write("\n")
                f.write(_field_table(msg['fields'], type_mappings, checksum))
                f.write("\n\n")
        else:
            f.write("_无_\n\n")

        f.write("---\n\n")

        f.write("## ROS → 电控（电控被动接收）\n\n")
        if tx_msgs:
            for msg in tx_msgs:
                reliable = msg.get('reliable', False)
                total_bytes = message_wire_payload_size(msg, type_mappings)
                f.write(f"### `{msg['name']}` — ID `{msg['id']:#04x}`\n\n")
                _write_message_meta(f, msg, 'sub_topic')
                f.write(f"- **数据段字节数（Len）**：`{total_bytes}`\n")
                if msg.get('notes'):
                    f.write(f"- **注意事项**：{msg['notes']}\n")
                if msg['name'] == 'Handshake' and require_handshake:
                    f.write("- **内置行为**：协议层收到握手包后自动回传本机 `PROTOCOL_HASH`，是否匹配由 ROS 端校验，MCU 侧无需编写代码。\n")
                if msg['name'] == 'Heartbeat':
                    f.write(f"- **内置行为**：ROS 端每 `{heartbeat_interval_ms} ms` 发起一次心跳，协议层自动按原样回传同一个 `count` 作为 ACK，MCU 侧无需编写代码。\n")
                if reliable:
                    f.write("- **可靠投递**：该消息启用 ACK/重传。ROS 端会在业务结构体 payload 后透明追加 1 字节 reliable seq；"
                            "该字节参与 `Len` 和校验，但不属于 `Packet_xxx` 业务结构体字段。生成的分发逻辑会先调用 `on_receive_xxx()`，回调返回后再自动 `send_Ack()`。\n")
                    f.write("- **投递语义**：ROS 节点进程存活期间的链路级 at-least-once。同 ID 消息按 FIFO 发送，ACK 丢失或串口断连重连时 ROS 端会持续重传到收到匹配 ACK；节点进程崩溃后的恢复不在保证范围内。`on_receive_xxx()` 可能被重复调用，回调实现需保证幂等。\n")
                f.write("\n")
                f.write(_field_table(
                    msg['fields'],
                    type_mappings,
                    checksum,
                    include_reliable_seq=reliable,
                ))
                f.write("\n\n")
        else:
            f.write("_无_\n\n")

        f.write("---\n\n")
        f.write("*文档由构建系统自动生成，版本以协议哈希为准。*\n")

        write_generated_file(output_path, f.getvalue())


