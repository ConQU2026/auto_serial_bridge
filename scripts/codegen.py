def extract_user_code(file_path):
    """从已存在的生成文件中提取 USER CODE 块。"""
    blocks = {}
    if not os.path.exists(file_path):
        return blocks

    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()

    pattern = re.compile(
        r'/\* USER CODE BEGIN (\w+) \*/(.*?)/\* USER CODE END \1 \*/', re.DOTALL)
    for key, code in pattern.findall(content):
        blocks[key] = code
    return blocks


def render_block(blocks, key):
    """渲染一个 USER CODE 块。"""
    content = blocks.get(key, "\n")
    return f"/* USER CODE BEGIN {key} */{content}/* USER CODE END {key} */\n"


def write_generated_file(output_path, content):
    """UTF-8 原子写入；内容未变化时跳过写入，避免无谓的重新编译。"""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    if os.path.exists(output_path):
        with open(output_path, 'r', encoding='utf-8') as f:
            if f.read() == content:
                return
    tmp_path = output_path + '.tmp'
    with open(tmp_path, 'w', encoding='utf-8') as f:
        f.write(content)
    os.replace(tmp_path, output_path)


